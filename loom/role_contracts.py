# -*- coding: utf-8 -*-
"""智库三人的落盘契约 + 「只挑不改」统一口径。

裁定原文:「2、按你建议来;3、统一口径,给选项或方案。」

两个问题都出在同一层:外部分析指出的「会干活但不留件」与「8 人只挑不改口径不一致」。
和主动性一样,**必须代码注入**——书里的角色提示词是各自副本,改出厂模板碰不到老书。
"""
from __future__ import annotations

# ── 1. 落盘契约:报告类产物必须有落点(否则只活在当次对话里)─────────────────
# 落点统一放 外置大脑/分析/(与语料分析、情绪曲线同一个"派生分析"目录,不污染事实源)。
# 一个角色可以有多件产物(2026-10-25 语料分析师加了「去AI味口径」),所以是元组。
OUTPUT_CONTRACT: dict[str, tuple[tuple[str, str], ...]] = {
    "战斗设计师": (("外置大脑/分析/战斗设计.md", "按卷或按场次一节,写清招式/克制/地形怎么用"),),
    "编辑总监": (("外置大脑/分析/质量报告.md", "按卷一节,写结构一致性与跨章通读结论"),),
    "批评家": (("外置大脑/分析/问题清单.md", "按章一节,只列问题与位置;发现即记录,别只留在对话里"),),
    # 2026-11-06 市场分析师入册（作者批准）：报告按卷一节，四件套=卖点四件套/题材趋势/上架时机/违禁比对
    "市场分析师": (("外置大脑/分析/市场分析.md",
                    "按卷一节:卖点四件套逐项过(书名/简介/题材/首章)、题材与趋势、上架与推荐时机、违禁比对"),),
    # 「让作者能靠着和他对话,优化去AI味逻辑」:
    # 代码侧的检测句式一个字不许模型改,但「哪些句子是我的签名句」「哪些表达我绝不这么写」
    # 「跨句号的。是算不算」这三件是作者自己的偏好,写成数据,由 aitell.load_policy 每次读。
    "语料分析师": (
        ("外置大脑/分析/语料分析.md", "词频/句式/节奏的结论,覆盖写;是参考数据,不是硬约束"),
        ("外置大脑/分析/去AI味口径.md",
         "三节:「豁免句」逐字抄作者原话、「额外禁用表达」一行一条、「跨句号翻转」只写 算 或 不算"),
    ),
}

# ── 2. 统一口径:发现问题必须给选项或方案(批评家/编辑总监/知识顾问)──────────────
ADVICE_RULE = """## 你给结论的口径(全员统一)
**只指出问题不算交付。** 发现一个问题,必须同时给出**2~3 个可选处理方式**,每个都写清:
- 这么做要付什么代价(改动范围 / 与已有设定是否冲突 / 会不会拖慢节奏);
- 你更推荐哪一个,以及为什么。
不要只给一个方案,也不要只列问题让作者自己想。作者可能不采纳,但必须有的挑。
"""

ADVICE_ROLES = ("批评家", "编辑总监", "知识顾问", "市场分析师")


def contract_text(role: str) -> str:
    """该角色的落盘契约段落。空串 = 这个角色不产出报告类产物。"""
    hits = OUTPUT_CONTRACT.get((role or "").strip())
    if not hits:
        return ""
    lines = ["## 你的产物落在哪（别让报告只活在对话里）"]
    for rel, how in hits:
        lines.append(f"- `{rel}` —— {how}。")
    rel0 = hits[0][0]
    lines.append(
        f"要写就用「提设定」把内容提成候选卡,落点写 `{rel0}#小节名`(小节名自定,"
        f"如「第3卷·终战」);作者拍板后才落盘,和别的设定一样。"
        "同一个文件可以多次追加不同小节;不要把整份文件重写一遍。")
    return "\n".join(lines)


def advice_text(role: str) -> str:
    return ADVICE_RULE if (role or "").strip() in ADVICE_ROLES else ""
