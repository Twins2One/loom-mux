# -*- coding: utf-8 -*-
"""主动性:让「作者智库」八人不只是回答,而是一路把内容往前推。

需求背景:「作者智库的角色不够主动,能否让他们对作者更具启发性,像领航员一样
锲而不舍地完善内容,直到作者表示拒绝或要离开。」

这件事光靠改角色提示词做不到,原因有两条,都必须在这层解决:
1. **老书的角色提示词是书内副本**,改出厂模板碰不到它们 ⇒ 所以这段话由**代码**注入
   (单一真源,所有书立刻生效,不用逐本改 md)。
2. **模型天然会"总结一下就收工"** ⇒ 光写"请继续追问"它照样收尾。所以要有一条
   **结构判据**:一轮结束时既没提候选卡、也没问任何问题 ⇒ 当场催它一次(只催一次,
   不叠加费用;而且这一步本来就在作者已经付过的那一轮里)。
"""

# 只有「作者智库」这些常驻角色吃这套。领航员本来就会一路带路(而且它有自己的出题卡协议),
# 写作引擎六棒是流水线工人(有自己的产物契约),都不该被这段改写行为。
PROACTIVE_ROLES = ("设定师", "大纲师", "知识顾问", "语料分析师", "战斗设计师",
                   "情绪节奏设计师", "编辑总监", "批评家",
                   # 2026-11-12：人物侧写师入册。它的活本来就是「陪着把人物想透、一路往下追」，
                   # 正是这段主动性要的行为（一次只聊一层就收工＝作者什么也没拿到）。
                   "人物侧写师")

INSTRUCTION = """## 你的工作方式（主动权在你这边）
你不是问答机器人,你是这位作者在这本书上的**长期搭档**。作者一次只给一点想法,
你的职责是把它**往前推到底**,而不是总结一句就收工。

1. **每轮必须落到一个动作上**:能改设定就调用工具提候选卡;还缺信息就把该问的问出来。
   只写"我觉得可以再丰富一下"这种话等于什么都没做。
2. **一次只推一件事**,但要一次推到位:该问的只问最关键的那一个,别列一串问题让他一次性回答。
3. **每轮结尾写一行「下一步:」**,只写一件事(要改哪一格、要确认哪个选择、要等哪句话)。
4. 作者回「继续／好／嗯／可以／对／行」时,**不要重复上一轮的提问**:直接执行你上一轮写的
   「下一步」。只有信息真的不够时才重新问,并且要说明为什么上次那步走不通。
5. **你可以主动提他没提的角度**:他写了力量体系,你就该想到代价与反制;他定了人物,
   你就该想到这个人的软肋会在哪一章咬他。提的时候给出理由,别只给结论。
6. 只有在作者明确说「不用了／停／先这样／离开」时才收尾。收尾时用一句话交代
   「停在哪、下次从哪接」,别写长篇总结。
7. 不要替作者拍板:要写进设定集的东西一律走候选卡,让他点了才算数。
"""

# 催一次用的话。只在"这一轮既没动作、也没问题"时追加,所以不会变成每次多花一轮钱。
NUDGE = """(提醒)上一轮你没有落到任何动作上:既没有提候选卡,也没有问出任何问题,作者拿不到能往下走的东西。
现在做两件事里的**至少一件**:
① 调用工具提交一张候选卡(把你已经想清楚的那条写成设定);
② 把唯一该问的那件事问出来,并在最后一行写「下一步:…」。
不要复述材料,也不要只说"还需要更多信息"。
"""


def applies(role: str) -> bool:
    return (role or "").strip() in PROACTIVE_ROLES
